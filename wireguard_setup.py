def parse_wireguard_conf_text(conf_text):
    """Parses standard WireGuard configuration text (from warp generator) into a dict."""
    config = {
        "private_key": "",
        "peer_public_key": "bmXOC+F1FxEMF9dyiK2H5/1SUtzH0JuVo51h2wPfgyo=",
        "endpoint": "engage.cloudflareclient.com:2408",
        "address": "172.16.0.2/32",
        "reserved": "",
        "dns": "1.1.1.1"
    }
    current_section = None
    for raw_line in conf_text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            # Check for commented reserved field, e.g. # Reserved = [217, 102, 12]
            if "Reserved" in line and "=" in line:
                val = line.split("=", 1)[1].strip()
                config["reserved"] = val
            continue
        if line.startswith("[") and line.endswith("]"):
            current_section = line[1:-1].strip().lower()
            continue
        if "=" in line:
            key, val = [part.strip() for part in line.split("=", 1)]
            key_lower = key.lower()
            if current_section == "interface":
                if key_lower == "privatekey":
                    config["private_key"] = val
                elif key_lower == "address":
                    # Take first IPv4 address if multiple are comma-separated
                    config["address"] = val.split(",")[0].strip()
                elif key_lower == "dns":
                    config["dns"] = val.split(",")[0].strip()
            elif current_section == "peer":
                if key_lower == "publickey":
                    config["peer_public_key"] = val
                elif key_lower == "endpoint":
                    config["endpoint"] = val
                elif key_lower == "reserved":
                    config["reserved"] = val
    return config


def auto_register_cloudflare_warp():
    """
    Automatically registers a fresh Cloudflare WARP account via Cloudflare REST API.
    Zero-configuration: generates a Curve25519 keypair and obtains a valid WARP IP.
    """
    logger.info("Registering new Cloudflare WARP client key via Cloudflare API...")
    try:
        import secrets
        import base64
        from cryptography.hazmat.primitives.asymmetric import x25519

        priv_bytes = bytearray(secrets.token_bytes(32))
        priv_bytes[0] &= 248
        priv_bytes[31] &= 127
        priv_bytes[31] |= 64
        private_key = x25519.X25519PrivateKey.from_private_bytes(bytes(priv_bytes))
        pub_b64 = base64.b64encode(private_key.public_key().public_bytes_raw()).decode()
        priv_b64 = base64.b64encode(bytes(priv_bytes)).decode()

        url = "https://api.cloudflareclient.com/v0a2158/reg"
        payload = json.dumps({
            "key": pub_b64,
            "install_id": "",
            "fcm_token": "",
            "tos": "2020-09-01T00:00:00.000Z",
            "model": "PC",
            "serial_number": "",
            "locale": "en_US"
        }).encode("utf-8")

        req = urllib.request.Request(url, data=payload, headers={
            "User-Agent": "okhttp/3.12.1",
            "Content-Type": "application/json"
        })
        with urllib.request.urlopen(req, timeout=12) as resp:
            res = json.loads(resp.read().decode("utf-8"))
            v4_addr = res.get("config", {}).get("interface", {}).get("addresses", {}).get("v4", "172.16.0.2")
            peers = res.get("config", {}).get("peers", [{}])
            peer = peers[0] if peers else {}
            endpoint = peer.get("endpoint", {}).get("host", "engage.cloudflareclient.com:2408")
            peer_pub = peer.get("public_key", "bmXOC+F1FxEMF9dyiK2H5/1SUtzH0JuVo51h2wPfgyo=")
            logger.info("🎉 Successfully auto-registered Cloudflare WARP! IPv4: %s", v4_addr)
            return {
                "private_key": priv_b64,
                "peer_public_key": peer_pub,
                "endpoint": endpoint,
                "address": f"{v4_addr}/32",
                "reserved": "",
                "dns": "1.1.1.1"
            }
    except Exception as e:
        logger.warning(f"Cloudflare WARP auto-registration failed: {e}. Falling back to environment WARP configuration.")
        return {
            "private_key": os.environ.get("WG_PRIVATE_KEY", ""),
            "peer_public_key": os.environ.get("WG_PEER_PUBLIC_KEY", ""),
            "endpoint": os.environ.get("WG_ENDPOINT", "engage.cloudflareclient.com:2408"),
            "address": os.environ.get("WG_ADDRESS", "172.16.0.2/32"),
            "reserved": os.environ.get("WG_RESERVED", ""),
            "dns": "1.1.1.1"
        }


def get_wireguard_env_config():
    """Extracts WireGuard WARP configuration from environment variables or local conf files."""
    # 1. Check if raw config text is provided in environment
    raw_conf = os.environ.get("WARP_CONF") or os.environ.get("WG_CONF_CONTENT") or ""
    if raw_conf.strip():
        parsed = parse_wireguard_conf_text(raw_conf)
        if parsed.get("private_key"):
            return parsed

    # 2. Check if a local config file exists (warp.conf, wireguard.conf, wg0.conf)
    for candidate in ["warp.conf", "wireguard.conf", "wg0.conf"]:
        if os.path.exists(candidate):
            try:
                with open(candidate, "r", encoding="utf-8") as f:
                    parsed = parse_wireguard_conf_text(f.read())
                    if parsed.get("private_key"):
                        logger.info(f"Loaded WireGuard configuration from local file: {candidate}")
                        return parsed
            except Exception as e:
                logger.warning(f"Error reading {candidate}: {e}")

    # 3. Fallback to individual environment variables
    private_key = os.environ.get("WG_PRIVATE_KEY", "").strip()
    peer_public_key = os.environ.get("WG_PEER_PUBLIC_KEY", "bmXOC+F1FxEMF9dyiK2H5/1SUtzH0JuVo51h2wPfgyo=").strip()
    endpoint = os.environ.get("WG_ENDPOINT", "engage.cloudflareclient.com:2408").strip()
    address = os.environ.get("WG_ADDRESS", "172.16.0.2/32").strip()
    reserved = os.environ.get("WG_RESERVED", "").strip()
    dns = os.environ.get("WG_DNS", "1.1.1.1").strip()
    
    if private_key:
        return {
            "private_key": private_key,
            "peer_public_key": peer_public_key,
            "endpoint": endpoint,
            "address": address,
            "reserved": reserved,
            "dns": dns
        }

    # 4. If no private key provided, auto-register a fresh Cloudflare WARP account
    return auto_register_cloudflare_warp()


def write_wireproxy_conf(conf_path="wireproxy.conf", config=None):
    """Generates a wireproxy configuration file."""
    if config is None:
        config = get_wireguard_env_config()
        
    if not config["private_key"]:
        logger.warning("No WG_PRIVATE_KEY provided. Cannot generate wireproxy.conf.")
        return False

    lines = [
        "[Interface]",
        f"Address = {config['address']}",
        f"PrivateKey = {config['private_key']}",
        f"DNS = {config['dns']}",
        "MTU = 1280",
    ]
    if config.get("reserved"):
        lines.append(f"Reserved = {config['reserved']}")
        
    lines.extend([
        "",
        "[Peer]",
        f"PublicKey = {config['peer_public_key']}",
        f"Endpoint = {config['endpoint']}",
        "AllowedIPs = 0.0.0.0/0, ::/0",
        "PersistentKeepalive = 15",
        "",
        "[http]",
        "BindAddress = 127.0.0.1:1080",
        "",
        "[socks5]",
        "BindAddress = 127.0.0.1:1081",
        ""
    ])

    with open(conf_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    logger.info(f"Generated wireproxy configuration at {conf_path}")
    return True


def write_wg_quick_conf(conf_path="/etc/wireguard/wg0.conf", config=None):
    """Generates standard wg0.conf for wg-quick."""
    if config is None:
        config = get_wireguard_env_config()

    if not config["private_key"]:
        return False

    lines = [
        "[Interface]",
        f"PrivateKey = {config['private_key']}",
        f"Address = {config['address']}",
        f"DNS = {config['dns']}",
        "MTU = 1280",
        "",
        "[Peer]",
        f"PublicKey = {config['peer_public_key']}",
        f"Endpoint = {config['endpoint']}",
        "AllowedIPs = 0.0.0.0/0, ::/0",
        "PersistentKeepalive = 15",
        ""
    ]
    try:
        os.makedirs(os.path.dirname(conf_path), exist_ok=True)
        with open(conf_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
        logger.info(f"Generated wg-quick configuration at {conf_path}")
        return True
    except Exception as e:
        logger.warning(f"Could not write {conf_path}: {e}")
        return False


def install_wireproxy(binary_path="./wireproxy"):
    """Downloads and installs the wireproxy standalone binary on Linux."""
    if os.path.exists(binary_path) and os.access(binary_path, os.X_OK):
        logger.info(f"wireproxy binary already available at {binary_path}")
        return binary_path

    if platform.system() != "Linux":
        logger.warning(f"Auto-download of wireproxy is only pre-configured for Linux. Current OS: {platform.system()}")
        return None

    logger.info(f"Downloading wireproxy from {WIREPROXY_LINUX_AMD64_URL}...")
    import tarfile
    tar_path = "/tmp/wireproxy.tar.gz"
    try:
        urllib.request.urlretrieve(WIREPROXY_LINUX_AMD64_URL, tar_path)
        with tarfile.open(tar_path, "r:gz") as tar:
            tar.extractall(path=os.path.dirname(os.path.abspath(binary_path)))
        if os.path.exists(binary_path):
            os.chmod(binary_path, 0o755)
            logger.info(f"wireproxy successfully extracted and made executable: {binary_path}")
            return binary_path
    except Exception as e:
        logger.error(f"Failed to download or extract wireproxy: {e}")
    finally:
        if os.path.exists(tar_path):
            os.remove(tar_path)
    return None


def test_proxy_connection(proxy_url="http://127.0.0.1:1080"):
    """Tests if the proxy is forwarding traffic through Cloudflare WARP."""
    logger.info(f"Verifying connection through proxy: {proxy_url}...")
    try:
        proxy_handler = urllib.request.ProxyHandler({'http': proxy_url, 'https': proxy_url})
        opener = urllib.request.build_opener(proxy_handler)
        req = urllib.request.Request("https://www.cloudflare.com/cdn-cgi/trace", headers={"User-Agent": "curl/7.68.0"})
        with opener.open(req, timeout=10) as resp:
            data = resp.read().decode("utf-8")
            warp_status = "off"
            ip = "unknown"
            for line in data.splitlines():
                if line.startswith("warp="):
                    warp_status = line.split("=", 1)[1]
                elif line.startswith("ip="):
                    ip = line.split("=", 1)[1]
            logger.info(f"✅ Cloudflare WARP Proxy Active! IP: {ip} | WARP: {warp_status}")
            return True, ip, warp_status
    except Exception as e:
        logger.warning(f"Proxy verification check failed: {e}")
        return False, None, None


def is_socks5_alive(host="127.0.0.1", port=1081):
    """Probes whether SOCKS5 proxy port is open and actively accepting connections."""
    import socket
    try:
        with socket.create_connection((host, port), timeout=0.8):
            return True
    except Exception:
        return False


def is_http_proxy_alive(host="127.0.0.1", port=1080):
    """Probes whether HTTP proxy port is open and actively accepting connections."""
    import socket
    try:
        with socket.create_connection((host, port), timeout=0.8):
            return True
    except Exception:
        return False


def clean_proxy_env_if_dead():
    """If proxy is unreachable, cleans up environment variables so urllib, requests, and Pyrogram work directly."""
    if not is_http_proxy_alive("127.0.0.1", 1080) and not is_socks5_alive("127.0.0.1", 1081):
        for k in ["HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY", "http_proxy", "https_proxy", "all_proxy", "USE_VPN_PROXY"]:
            if k in os.environ:
                os.environ.pop(k, None)
        logger.info("ℹ️ Local proxy on 127.0.0.1 is not reachable. Cleared proxy env vars to ensure clean direct connection.")


def get_pyrogram_proxy():
    """Returns Pyrogram proxy dict for SOCKS5 proxy via WireGuard ONLY if actively alive."""
    if os.environ.get("USE_VPN_PROXY") == "true" or os.environ.get("ALL_PROXY"):
        if is_socks5_alive("127.0.0.1", 1081):
            logger.info("✅ SOCKS5 proxy on 127.0.0.1:1081 is active. Routing Pyrogram via WireGuard.")
            return dict(scheme="socks5", hostname="127.0.0.1", port=1081)
        else:
            logger.warning("⚠️ SOCKS5 proxy on 127.0.0.1:1081 is not reachable. Using direct connection for Pyrogram.")
    return None


def enforce_wireguard_in_python():
    """
    Enforces WireGuard proxy across all Python libraries:
    - Sets HTTP_PROXY, HTTPS_PROXY, ALL_PROXY, http_proxy, https_proxy, all_proxy
    - Sets NO_PROXY for local services and GitHub API
    - Installs default urllib.request opener
    - Patches requests.Session default proxies
    """
    proxy_http = "http://127.0.0.1:1080"
    proxy_socks = "socks5://127.0.0.1:1081"
    
    for v in ["HTTP_PROXY", "HTTPS_PROXY", "http_proxy", "https_proxy"]:
        os.environ[v] = proxy_http
    for v in ["ALL_PROXY", "all_proxy"]:
        os.environ[v] = proxy_socks
    no_proxy_str = "localhost,127.0.0.1,0.0.0.0,github.com,api.github.com,raw.githubusercontent.com"
    os.environ["NO_PROXY"] = no_proxy_str
    os.environ["no_proxy"] = no_proxy_str
    os.environ["USE_VPN_PROXY"] = "true"

    try:
        proxy_handler = urllib.request.ProxyHandler({'http': proxy_http, 'https': proxy_http})
        opener = urllib.request.build_opener(proxy_handler)
        urllib.request.install_opener(opener)
    except Exception as e:
        logger.warning(f"urllib proxy patch warning: {e}")

    try:
        import requests
        _old_init = requests.Session.__init__
        def _new_init(self, *args, **kwargs):
            _old_init(self, *args, **kwargs)
            self.proxies = {'http': proxy_http, 'https': proxy_http}
        requests.Session.__init__ = _new_init
    except Exception:
        pass


def setup_and_start_wireguard():
    """Main orchestration function to setup and run WireGuard / wireproxy."""
    # 0. Check if wireproxy is already active on 127.0.0.1:1080
    ok, ip, warp = test_proxy_connection("http://127.0.0.1:1080")
    if ok:
        enforce_wireguard_in_python()
        logger.info(f"🛡️ WireGuard WARP Proxy already active! Outgoing IP: {ip} | WARP: {warp}")
        return True

    config = get_wireguard_env_config()
    if not config or not config.get("private_key"):
        logger.warning("Could not obtain WireGuard configuration from environment.")
        config = {
            "private_key": os.environ.get("WG_PRIVATE_KEY", ""),
            "peer_public_key": os.environ.get("WG_PEER_PUBLIC_KEY", ""),
            "endpoint": os.environ.get("WG_ENDPOINT", "engage.cloudflareclient.com:2408"),
            "address": os.environ.get("WG_ADDRESS", "172.16.0.2/32"),
            "reserved": os.environ.get("WG_RESERVED", ""),
            "dns": "1.1.1.1"
        }

    logger.info("🛡️ Initializing Cloudflare WARP integration...")
    
    # 1. Generate wireproxy configuration
    conf_file = "wireproxy.conf"
    write_wireproxy_conf(conf_file, config)

    # 2. If running on Linux (e.g. GitHub Actions runner)
    if platform.system() == "Linux":
        bin_path = install_wireproxy("./wireproxy")
        if bin_path and os.path.exists(bin_path):
            logger.info("Starting wireproxy daemon in background on 127.0.0.1:1080 (HTTP) & 127.0.0.1:1081 (SOCKS5)...")
            log_f = open("/tmp/wireproxy.log", "w")
            proc = subprocess.Popen([bin_path, "-c", conf_file], stdout=log_f, stderr=subprocess.STDOUT)
            time.sleep(3)
            
            # Verify proxy
            ok, ip, warp = test_proxy_connection("http://127.0.0.1:1080")
            if ok:
                enforce_wireguard_in_python()
                gh_env = os.environ.get("GITHUB_ENV")
                if gh_env and os.path.exists(gh_env):
                    with open(gh_env, "a", encoding="utf-8") as f:
                        f.write("USE_VPN_PROXY=true\n")
                        f.write("HTTP_PROXY=http://127.0.0.1:1080\n")
                        f.write("HTTPS_PROXY=http://127.0.0.1:1080\n")
                        f.write("ALL_PROXY=socks5://127.0.0.1:1081\n")
                        f.write("http_proxy=http://127.0.0.1:1080\n")
                        f.write("https_proxy=http://127.0.0.1:1080\n")
                        f.write("all_proxy=socks5://127.0.0.1:1081\n")
                        f.write("NO_PROXY=localhost,127.0.0.1,0.0.0.0,github.com,api.github.com,raw.githubusercontent.com\n")
                        f.write("no_proxy=localhost,127.0.0.1,0.0.0.0,github.com,api.github.com,raw.githubusercontent.com\n")
                logger.info(f"🎉 WireGuard WARP Proxy active! All traffic routed through WireGuard IP: {ip} | WARP: {warp}")
                return True
            else:
                logger.warning("wireproxy did not respond in 3s. Continuing bot startup.")
                clean_proxy_env_if_dead()

    return False


if __name__ == "__main__":
    setup_and_start_wireguard()
